def get_type(code):
    """يعيد نوع الخطأ لرمزه، أو OTHER_TYPE لرمز غير معروف (مع حفظ الرمز الخام
    في النتيجة عند من يستدعيه)."""
    if not code:
        return OTHER_TYPE
    code = str(code).strip().upper().replace("_", "-")
    return ERROR_TYPES.get(code, OTHER_TYPE)


def category_name(category_code):
    cat = CATEGORIES.get(category_code)
    return cat.name if cat else "غير مصنَّف"


def normalize_severity(value, fallback):
    value = str(value or "").strip()
    aliases = {
        "critical": "حرج",
        "حرجة": "حرج",
        "حرِج": "حرج",
        "major": "كبير",
        "كبيرة": "كبير",
        "moderate": "متوسط",
        "medium": "متوسط",
        "متوسطة": "متوسط",
        "minor": "بسيط",
        "بسيطة": "بسيط",
        "low": "بسيط",
    }
    value = aliases.get(value.lower(), value)
    return value if value in SEVERITIES else fallback


def normalize_detection(value, fallback):
    value = str(value or "").strip()
    aliases = {
        "deterministic": "قطعي",
        "قطعية": "قطعي",
        "rule": "قطعي",
        "inferential": "استدلالي",
        "استدلالية": "استدلالي",
        "indicator": "مؤشر اشتباه",
        "suspicion": "مؤشر اشتباه",
        "مؤشر": "مؤشر اشتباه",
    }
    value = aliases.get(value.lower(), value)
    return value if value in DETECTIONS else fallback


def max_severity(severities):
    """أعلى خطورة في قائمة، أو None إن كانت فارغة."""
    best = None
    for s in severities:
        if s in SEVERITY_RANK and (best is None or SEVERITY_RANK[s] > SEVERITY_RANK[best]):
            best = s
    return best


def verdict_for(severities):
    """الحكم النهائي على الصف من خطورات أخطائه:
    لا أخطاء → مقبول · حرج/كبير → مرفوض · متوسط/بسيط فقط → يحتاج مراجعة."""
    top = max_severity(severities)
    if top is None:
        return VERDICT_ACCEPTED
    if top in ("حرج", "كبير"):
        return VERDICT_REJECTED
    return VERDICT_REVIEW


def taxonomy_table_text():
    """جدول التصنيف بصيغة نصية مضغوطة للبرومت (رمز | نوع | تعريف | خطورة افتراضية)."""
    lines = []
    for cat in CATEGORIES.values():
        lines.append(f"\n### {cat.code} — {cat.name}: {cat.description}")
        for t in ERROR_TYPES.values():
            if t.category != cat.code:
                continue
            flags = []
            if t.sharia_default:
                flags.append("حساسية شرعية")
            if t.detection_default != "استدلالي":
                flags.append(t.detection_default)
            suffix = f" [{'، '.join(flags)}]" if flags else ""
            lines.append(
                f"- {t.code} | {t.name} | {t.definition} | الخطورة الافتراضية: {t.default_severity}{suffix}"
            )
    lines.append(f"\n- {OTHER_CODE} | {OTHER_TYPE.name} | {OTHER_TYPE.definition}")
    return "\n".join(lines)


def taxonomy_rows():
    """صفوف مسطّحة للتصدير إلى ورقة «التصنيف» في Excel."""
    rows = []
    for t in ERROR_TYPES.values():
        rows.append(
            {
                "رمز الفئة": t.category,
                "الفئة": category_name(t.category),
                "رمز النوع": t.code,
                "نوع الخطأ": t.name,
                "التعريف": t.definition,
                "الخطورة الافتراضية": t.default_severity,
                "حساسية شرعية افتراضية": "نعم" if t.sharia_default else "لا",
                "طريقة الكشف الافتراضية": t.detection_default,
                "المطلوب": t.required_action,
            }
        )
    return rows
